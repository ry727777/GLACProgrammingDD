#include<stdio.h>

int main(){
	// Format Specifier
	printf("%d %d %d \n",23,45,50);  // %d or %i used to print integer
	printf("%.2f\n",45.568); // %f is used to print decimal value, %.2f used to print up to 2 decimal value
	printf("%s\n","Hello"); // % s can be used to print string
	printf("%c",'A'); // %c used to print character value
	return 0;
}
